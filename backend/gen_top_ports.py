"""Regenerate backend/app/top_ports.txt from nmap's own port-frequency list.

    python -m backend.gen_top_ports                      # finds nmap-services automatically
    python -m backend.gen_top_ports "C:/Program Files (x86)/Nmap/nmap-services"

The generated file is committed, so every laptop scans exactly the same ports
whatever nmap version it has installed (NFR-05).
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

TOP_N = 1000

# Catalog services whose default port is not in nmap's top 1000 (FR-04 asks for the top 1000 "at least").
CATALOG_EXTRA = {1883: "mqtt", 6379: "redis", 27017: "mongodb"}

OUTPUT = Path(__file__).parent / "app" / "top_ports.txt"

CANDIDATES = [
    Path("C:/Program Files (x86)/Nmap/nmap-services"),
    Path("C:/Program Files/Nmap/nmap-services"),
    Path("/usr/share/nmap/nmap-services"),
    Path("/usr/local/share/nmap/nmap-services"),
    Path("/opt/homebrew/share/nmap/nmap-services"),
]


def find_nmap_services() -> Path | None:
    nmap = shutil.which("nmap")
    if nmap:
        here = Path(nmap).resolve().parent
        CANDIDATES[:0] = [here / "nmap-services", here.parent / "share" / "nmap" / "nmap-services"]
    return next((p for p in CANDIDATES if p.is_file()), None)


def top_tcp_ports(services_file: Path, n: int = TOP_N) -> list[int]:
    """The n TCP ports with the highest open-frequency, the same ranking nmap's --top-ports uses."""
    ranked = []
    for line in services_file.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 3 or not parts[1].endswith("/tcp"):
            continue
        ranked.append((-float(parts[2]), int(parts[1].split("/")[0])))
    ranked.sort()
    return [port for _, port in ranked[:n]]


def main(argv: list[str]) -> int:
    services = Path(argv[0]) if argv else find_nmap_services()
    if not services or not services.is_file():
        print("nmap-services not found. Install nmap or pass the path to its nmap-services file.", file=sys.stderr)
        return 1

    top = top_tcp_ports(services)
    extra = sorted(p for p in CATALOG_EXTRA if p not in top)
    ports = sorted(set(top) | set(extra))

    header = [
        f"# Top {TOP_N} TCP ports by nmap frequency, plus catalog ports outside that list.",
        f"# Generated by: python -m backend.gen_top_ports  (from {services.name})",
        f"# Catalog extras: {', '.join(f'{p} ({CATALOG_EXTRA[p]})' for p in extra) or 'none'}",
        "# One port per line. Do not edit by hand; regenerate instead.",
    ]
    OUTPUT.write_text("\n".join(header + [str(p) for p in ports]) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT} with {len(ports)} TCP ports ({len(top)} top + {len(extra)} catalog extras)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
